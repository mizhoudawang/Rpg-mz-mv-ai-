//---------------------------------------------------------- 定位 www/
function findWww(p) {
  if (fs.existsSync(path.join(p, 'data', 'System.json'))) return p;
  if (fs.existsSync(path.join(p, 'www', 'data', 'System.json'))) return path.join(p, 'www');
  const stack = [[p, 0]];
  while (stack.length) {
    const [d, n] = stack.shift();
    if (n > 3) continue;
    if (fs.existsSync(path.join(d, 'data', 'System.json'))) return d;
    if (fs.existsSync(path.join(d, 'www', 'data', 'System.json'))) return path.join(d, 'www');
    let entries = [];
    try { entries = fs.readdirSync(d, { withFileTypes: true }); } catch (e) { continue; }
    for (const e of entries) {
      if (e.isDirectory() && !e.name.startsWith('-') && e.name !== 'node_modules') stack.push([path.join(d, e.name), n + 1]);
    }
  }
  return null;
}
/** 【v2.9.16】嗅探「这是不是**别的** RPG Maker 引擎」。
 *  RGSS（XP / VX / VX Ace）用 Ruby，插件体系与 MV/MZ 完全不同 —— 本插件不可能支持。
 *  给玩家一句说得通的话，而不是「找不到 data/System.json，确认一下路径」
 *  （RGSS 玩家会以为是自己路径填错，反复试）。 */
function sniffEngine(root) {
  const marks = [
    ['XP', /^(Game\.rgssad|RGSS1\d\d[Ee]?\.dll)$/i],
    ['VX', /^(Game\.rgss2a|RGSS2\d\d[Ee]?\.dll)$/i],
    ['VX Ace', /^(Game\.rgss3a|RGSS3\d\d[Ee]?\.dll)$/i]
  ];
  const stack = [[root, 0]];
  while (stack.length) {
    const cur = stack.shift(), d = cur[0], n = cur[1];
    if (n > 2) continue;
    let es = [];
    try { es = fs.readdirSync(d); } catch (e) { continue; }
    for (const e of es) {
      for (const m of marks) if (m[1].test(e)) return m[0];
      const p = path.join(d, e);
      let st; try { st = fs.statSync(p); } catch (x) { continue; }
      if (st.isDirectory()) stack.push([p, n + 1]);
    }
  }
  return null;
}
