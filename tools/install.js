// 4a-2) 隔离「上一部作品遗留的线索包」。
//   历史版本曾把 persona_input.json / lorebook_input.json 随安装铺出去，于是别人的游戏里
//   可能已经躺着一份**上一部作品**的清单。它不会自动消失（我们也不覆盖），而「一键生成」
//   看到文件已存在就会跳过重建 —— 结果永远是错的。这里主动认出来并改名隔离。
//   判据：① 新文件带 gameTitle 指纹，与当前世界书的游戏名不符 → 外来；
//         ② 老文件没指纹，就看它引用的角色 key 与当前世界书**一个都对不上** → 外来。
function staleStamp() {
  const d = new Date(), p = n => String(n).padStart(2, '0');
  return d.getFullYear() + p(d.getMonth() + 1) + p(d.getDate()) + '-' + p(d.getHours()) + p(d.getMinutes()) + p(d.getSeconds());
}
function quarantineStale(file, why) {
  try {
    const bak = file + '.stale-' + staleStamp();
    fs.renameSync(file, bak);
    console.log('  ⚠ ' + path.basename(file) + ' 是别的作品留下来的（' + why + '）');
    console.log('    已改名为 ' + path.basename(bak) + '，不会参与本次生成。');
    console.log('    进游戏点「生成角色人设 / 生成世界设定」会按本作重建（这是正常的，只跑一次）。');
    return true;
  } catch (e) { return false; }
}
try {
  const WBJ = path.join(AI_DIR, 'worldbook.json');
  if (fs.existsSync(WBJ)) {
    const wb = JSON.parse(fs.readFileSync(WBJ, 'utf8').replace(/^\uFEFF/, ''));
    const wbTitle = String((wb.game && (wb.game.title || wb.game.name)) || wb.gameTitle || '').trim();
    const keys = {};
    (wb.npcs || []).forEach(n => { if (n && n.key) keys[n.key] = 1; });
    /* persona_input.json —— 角色 key 交集判据 */
    const PI = path.join(AI_DIR, 'persona_input.json');
    let piStale = false;
    if (fs.existsSync(PI)) {
      try {
        const pi = JSON.parse(fs.readFileSync(PI, 'utf8').replace(/^\uFEFF/, ''));
        const piTitle = String(pi.gameTitle || '').trim();
        if (piTitle && wbTitle && piTitle !== wbTitle) {
          piStale = quarantineStale(PI, '写着「' + piTitle + '」，本作是「' + wbTitle + '」');
        } else {
          let total = 0, hit = 0;
          (pi.groups || []).forEach(g => (g.members || []).forEach(m => { total++; if (m && keys[m.key]) hit++; }));
          /* 【v2.9.0】判据用**命中率**，不是"一个都不命中"：key 的格式（M8:E5）是所有 MV 游戏
           * 通用的，跨游戏**必然**有个别巧合撞上（实测一份外来的清单命中率 1.9%）。
           * 同一部游戏重装/重生成时命中率接近 100%。取一半当界线。 */
          if (total > 0 && hit / total < 0.5) {
            piStale = quarantineStale(PI, '只有 ' + Math.round(hit / total * 100) + '% 的角色 key 对得上本作世界书（' + hit + '/' + total + '）');
          }
        }
      } catch (e) { }
    }
    /* lorebook_input.json —— 有指纹就比指纹；没指纹时，若上面已判定 persona_input 是外来的，
     * 那这一份几乎肯定是同一次复制带过来的，一并隔离（两者总是成对铺设/成对污染）。 */
    const LI = path.join(AI_DIR, 'lorebook_input.json');
    if (fs.existsSync(LI)) {
      try {
        const li = JSON.parse(fs.readFileSync(LI, 'utf8').replace(/^\uFEFF/, ''));
        const liTitle = String(li.gameTitle || '').trim();
        if (liTitle && wbTitle && liTitle !== wbTitle) {
          quarantineStale(LI, '写着「' + liTitle + '」，本作是「' + wbTitle + '」');
        } else if (!liTitle && piStale) {
          quarantineStale(LI, '与本作世界设定对不上（伴随那份外来的人设线索包一起被隔离）');
        }
      } catch (e) { }
    }
  }
} catch (e) { /* 隔离是尽力而为，失败不影响安装 */ }

