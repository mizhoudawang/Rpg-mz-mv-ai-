/** RPG Maker 编辑器的写法：头两行注释 + "var $plugins =\n[\n" + 逐条 JSON.stringify 用 ",\n" 连 + "\n];\n"
 *  实测可对原文件做无损 round-trip。 */
function parsePlugins(text) {
  const a = text.indexOf('['), b = text.lastIndexOf(']');
  if (a < 0 || b < a) throw new Error('plugins.js 里找不到 $plugins 数组');
  return JSON.parse(text.slice(a, b + 1));
}
function writePlugins(arr) {
  return '// Generated by RPG Maker.\n// Do not edit this file directly.\nvar $plugins =\n[\n'
    + arr.map(p => JSON.stringify(p)).join(',\n') + '\n];\n';
}
function backup(file) {
  const dir = path.dirname(file), base = path.basename(file);
  const cur = fs.readFileSync(file);
  // 内容与已有备份完全相同就不再堆一份（反复重装时特别有用，也保住最早那份原始文件）
  try {
    for (const f of fs.readdirSync(dir)) {
      if (f.startsWith(base + '.bak-') && fs.readFileSync(path.join(dir, f)).equals(cur)) {
        console.log('  备份 → 已有同内容备份 ' + f + '，跳过');
        return path.join(dir, f);
      }
    }
  } catch (e) { }
  const d = new Date();
  const p2 = n => String(n).padStart(2, '0');
  const stamp = d.getFullYear() + p2(d.getMonth() + 1) + p2(d.getDate()) + '-' + p2(d.getHours()) + p2(d.getMinutes()) + p2(d.getSeconds());
  const dst = file + '.bak-' + stamp;
  fs.copyFileSync(file, dst);
  console.log('  备份 → ' + path.basename(dst));
  return dst;
}

